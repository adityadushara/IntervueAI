/**
 * Live Gemini AI Engine & Supabase Integration Test Suite for IntervueAI
 * 
 * Verifies real Gemini AI API calls and end-to-end workflow:
 * - Live Job Description Analysis (structured plan, competency rubric, tailored questions)
 * - Live Conversational Interviewer (semantic answer analysis, adaptive follow-up probing)
 * - Live Structured Candidate Evaluation (6 core competencies, grounded transcript quotes, advisory recommendation)
 * - Live End-to-End Persistence into remote Supabase database
 * - Recruiter confidentiality & candidate payload isolation
 */

import * as fs from 'fs';
import * as path from 'path';

// Automatically load .env.local into process.env if present
const envLocalPath = path.resolve(process.cwd(), '.env.local');
const nodeProcess = process as unknown as { loadEnvFile?: (path: string) => void };
if (fs.existsSync(envLocalPath) && typeof nodeProcess.loadEnvFile === 'function') {
  nodeProcess.loadEnvFile(envLocalPath);
}

import { analyzeJobDescriptionWithGemini } from '../src/lib/gemini/analyzer';
import { processAdaptiveInterviewerTurn } from '../src/lib/gemini/interviewer';
import { evaluateCandidateInterviewWithGemini } from '../src/lib/gemini/evaluator';
import { createClient } from '@supabase/supabase-js';
import { 
  createInterviewInDb, 
  getInterviewByRawTokenFromDb, 
  getRecruiterInterviewsFromDb
} from '../src/lib/supabase/service';
import { POST as interactApi } from '../src/app/api/interviews/[token]/interact/route';
import { GET as getInterviewApi, PATCH as patchInterviewApi } from '../src/app/api/interviews/[token]/route';
import { JobConfiguration, CandidateAnswer, InterviewQuestion } from '../src/types/interview';

let passed = 0;
let failed = 0;

function assert(condition: boolean, title: string, details?: string) {
  if (condition) {
    passed++;
    console.log(`  \x1b[32m✔ PASS\x1b[0m ${title}`);
  } else {
    failed++;
    console.error(`  \x1b[31m✖ FAIL\x1b[0m ${title} - ${details || 'Assertion failed'}`);
  }
}

async function runLiveGeminiSuite() {
  console.log('\n======================================================');
  console.log('🤖 RUNNING REAL GEMINI AI INTEGRATION SUITE');
  console.log(`   Model: ${process.env.GEMINI_MODEL || 'gemini-3.5-flash'}`);
  console.log(`   API Key configured: ${Boolean(process.env.GEMINI_API_KEY)}`);
  console.log('======================================================\n');

  if (!process.env.GEMINI_API_KEY) {
    console.error('Fatal: GEMINI_API_KEY is not set in environment or .env.local.');
    process.exit(1);
  }

  const sampleJobConfig: JobConfiguration = {
    companyName: 'NovaCloud Global',
    jobTitle: 'Senior Cloud Systems Architect',
    jobDescription: 'Architect resilient multi-region cloud infrastructures, Kubernetes clusters, and zero-downtime distributed systems.',
    requiredSkills: ['Kubernetes', 'Terraform', 'Distributed Systems', 'AWS', 'PostgreSQL'],
    requiredExperience: '5+ years',
    seniorityLevel: 'Senior',
    interviewType: 'Technical',
    difficulty: 'Advanced',
    questionCount: 3,
    expectedDurationMinutes: 30,
    language: 'English',
  };

  // --------------------------------------------------------------------------
  // TEST GROUP 1: LIVE JOB DESCRIPTION ANALYSIS
  // --------------------------------------------------------------------------
  console.log('\x1b[36m--- Group 1: Live Job Description Analysis ---\x1b[0m');

  const analysisStartTime = Date.now();
  const planResult = await analyzeJobDescriptionWithGemini(sampleJobConfig);
  const analysisElapsed = Date.now() - analysisStartTime;

  assert(planResult.isAiGenerated === true, 
    'Job description analysis was generated by live Gemini AI (not fallback)');
  assert(typeof planResult.plan.interviewStructureSummary === 'string' && planResult.plan.interviewStructureSummary.length > 20, 
    'Gemini generated insightful interview structure summary');
  assert(Array.isArray(planResult.plan.competencyCategories) && planResult.plan.competencyCategories.length >= 2, 
    `Gemini defined structured competency categories (${planResult.plan.competencyCategories.length} categories)`);
  assert(Array.isArray(planResult.plan.difficultyProgression) && planResult.plan.difficultyProgression.length >= 2, 
    'Gemini generated difficulty progression ladder');
  assert(planResult.questions.length === sampleJobConfig.questionCount, 
    `Gemini generated requested number of questions (${planResult.questions.length} questions)`);
  assert(planResult.questions.every(q => q.text.length > 25), 
    'All generated questions have comprehensive technical depth');
  console.log(`     Latency: ${analysisElapsed}ms | Sample Q1: "${planResult.questions[0].text.substring(0, 60)}..."`);

  // --------------------------------------------------------------------------
  // TEST GROUP 2: LIVE ADAPTIVE CONVERSATIONAL INTERVIEWER TURN
  // --------------------------------------------------------------------------
  console.log('\n\x1b[36m--- Group 2: Live Adaptive Conversational Interviewer Turn ---\x1b[0m');

  const question1: InterviewQuestion = planResult.questions[0];
  const superficialAnswer = 'We use Kubernetes with pods and deploy them across AWS availability zones.';

  const turnStartTime = Date.now();
  const turnResult = await processAdaptiveInterviewerTurn({
    jobConfig: sampleJobConfig,
    currentQuestion: question1,
    candidateAnswerText: superficialAnswer,
    allQuestions: planResult.questions,
    previousAnswers: [],
    currentQuestionIndex: 0,
    totalQuestions: planResult.questions.length,
    elapsedSeconds: 120,
    maxDurationSeconds: 1800,
  });
  const turnElapsed = Date.now() - turnStartTime;

  assert(turnResult.isAiGenerated === true, 
    'Conversational turn was evaluated by live Gemini AI (not fallback)');
  assert(typeof turnResult.interviewerFeedback === 'string' && turnResult.interviewerFeedback.length > 10, 
    'Gemini provided natural conversational candidate feedback');
  assert(turnResult.hasFollowUp === true && Boolean(turnResult.followUpQuestion), 
    'Gemini identified knowledge gaps in brief answer and generated adaptive follow-up');
  assert(typeof turnResult.followUpQuestion?.text === 'string' && turnResult.followUpQuestion.text.length > 20, 
    'Adaptive follow-up question is substantial and technical');
  console.log(`     Latency: ${turnElapsed}ms`);
  console.log(`     Interviewer says: "${turnResult.interviewerFeedback}"`);
  console.log(`     Follow-up Q: "${turnResult.followUpQuestion?.text}"`);

  // --------------------------------------------------------------------------
  // TEST GROUP 3: LIVE STRUCTURED CANDIDATE EVALUATION
  // --------------------------------------------------------------------------
  console.log('\n\x1b[36m--- Group 3: Live Structured Candidate Evaluation ---\x1b[0m');

  const followUpQ = turnResult.followUpQuestion || {
    id: 'follow-up-1',
    questionNumber: 2,
    text: 'How do you handle zero-downtime rolling upgrades in Kubernetes across multiple worker nodes?',
    category: 'Cloud Infrastructure',
  };

  const candidateAnswers: CandidateAnswer[] = [
    {
      questionId: question1.id,
      questionText: question1.text,
      answerText: superficialAnswer,
      timeSpentSeconds: 120,
      submittedAt: new Date().toISOString(),
    },
    {
      questionId: followUpQ.id,
      questionText: followUpQ.text,
      answerText: 'To ensure zero downtime during cluster upgrades, we employ pod disruption budgets, topology spread constraints across 3 AZs, preStop lifecycle hooks with graceful termination periods, and blue/green worker node pool draining.',
      timeSpentSeconds: 240,
      submittedAt: new Date().toISOString(),
    },
    {
      questionId: planResult.questions[1].id,
      questionText: planResult.questions[1].text,
      answerText: 'For Terraform state management in multi-region environments, we separate root composition from component modules, enforce remote S3 backend with DynamoDB locking, and use automated Atlantis pull request validation.',
      timeSpentSeconds: 180,
      submittedAt: new Date().toISOString(),
    }
  ];

  const evalStartTime = Date.now();
  const evalResult = await evaluateCandidateInterviewWithGemini({
    jobConfig: sampleJobConfig,
    candidateInfo: { fullName: 'Jordan Blake', email: 'jordan@example.com' },
    questions: [...planResult.questions, followUpQ],
    answers: candidateAnswers,
    totalDurationSeconds: 540,
  });
  const evalElapsed = Date.now() - evalStartTime;

  assert(evalResult.isAiGenerated === true, 
    'Candidate evaluation was synthesized by live Gemini AI (not fallback)');
  const detailed = evalResult.detailed;
  assert(typeof detailed.overallScore === 'number' && detailed.overallScore >= 0 && detailed.overallScore <= 100, 
    `Gemini produced valid numeric overall score: ${detailed.overallScore}/100`);
  assert(typeof detailed.interviewSummary === 'string' && detailed.interviewSummary.length > 50, 
    'Gemini generated comprehensive interview synthesis');

  // Verify all 6 competencies
  const competencyKeys = [
    'technicalKnowledge',
    'problemSolving',
    'communication',
    'conceptualUnderstanding',
    'practicalReasoning',
    'roleSpecific'
  ] as const;

  for (const key of competencyKeys) {
    const comp = detailed.competencies[key];
    assert(!!comp && typeof comp.score === 'number' && comp.score >= 0 && comp.score <= 100, 
      `Competency "${key}" is evaluated with bounded score (${comp?.score}/100)`);
    assert(Array.isArray(comp?.evidence) && comp.evidence.length > 0, 
      `Competency "${key}" includes grounded transcript evidence citations`);
  }

  // Check grounded citations
  const allEvidence = Object.values(detailed.competencies).flatMap(c => c.evidence).join(' ');
  const referencesTranscript = allEvidence.toLowerCase().includes('kubernetes') || 
                               allEvidence.toLowerCase().includes('terraform') || 
                               allEvidence.toLowerCase().includes('pod disruption') ||
                               allEvidence.toLowerCase().includes('atlantis');
  assert(referencesTranscript, 
    'Evaluation evidence strictly quotes candidate answers without hallucination');

  // Check advisory recommendation
  const validRecs = ['Strongly Recommend', 'Recommend', 'Borderline', 'Not Recommended'];
  assert(validRecs.includes(detailed.hiringRecommendation), 
    `Gemini formulated recognized recommendation: ${detailed.hiringRecommendation}`);
  assert(typeof detailed.recommendationDisclaimer === 'string' && detailed.recommendationDisclaimer.toLowerCase().includes('advisory'), 
    'Evaluation explicitly includes advisory disclaimer notice');
  console.log(`     Latency: ${evalElapsed}ms | Overall Score: ${detailed.overallScore}/100 | Recommendation: ${detailed.hiringRecommendation}`);

  // --------------------------------------------------------------------------
  // TEST GROUP 4: LIVE END-TO-END SUPABASE PERSISTENCE & API WORKFLOW
  // --------------------------------------------------------------------------
  console.log('\n\x1b[36m--- Group 4: Live Supabase Persistence & API Integration ---\x1b[0m');

  const adminClient = createClient(
    process.env.NEXT_PUBLIC_SUPABASE_URL || 'https://tzmiipvvdavfkifwprhk.supabase.co',
    process.env.SUPABASE_SERVICE_ROLE_KEY || process.env.SUPABASE_SECRET_KEY || '',
    { auth: { persistSession: false, autoRefreshToken: false } }
  );

  const { data: existingProfiles } = await adminClient.from('profiles').select('id').limit(1);
  let recruiterId = existingProfiles?.[0]?.id;
  if (!recruiterId) {
    const { data: user } = await adminClient.auth.admin.createUser({
      email: `gemini_recruiter_${Date.now()}@intervue.ai`,
      password: 'Password123!@#',
      email_confirm: true,
      user_metadata: { full_name: 'Gemini Recruiter', company_name: 'NovaCloud Global' }
    });
    recruiterId = user?.user?.id;
  }

  const testCandidateName = `Gemini Live Test ${Date.now()}`;
  const testCandidateEmail = `gemini-test-${Date.now()}@example.com`;

  // 1. Create interview in live Supabase with Gemini structured plan and questions
  const rawToken = `inv-gemini-live-${Date.now()}-${Math.random().toString(36).substring(2, 8)}`;
  const jobConfigWithPlan = {
    ...sampleJobConfig,
    companyName: 'NovaCloud Global',
    structuredPlan: planResult.plan,
  };

  const created = await createInterviewInDb(
    jobConfigWithPlan,
    { expiration: '48 hours' },
    { fullName: testCandidateName, email: testCandidateEmail },
    rawToken,
    planResult.questions,
    recruiterId
  );

  assert(!!created && !!created.token && !!created.id, 
    'Created interview record in remote Supabase with raw token');

  // 2. Query interview by raw token (uses SHA-256 hash lookup in Supabase)
  const fetchedByToken = await getInterviewByRawTokenFromDb(created.token);
  assert(!!fetchedByToken && fetchedByToken.id === created.id, 
    'Resolved interview from live Supabase using SHA-256 token hash');
  assert(fetchedByToken?.jobConfig.structuredPlan?.interviewStructureSummary === planResult.plan.interviewStructureSummary, 
    'Supabase persisted and returned Gemini structuredPlan in job_configurations');
  assert(fetchedByToken?.questions.length === 3, 
    'Supabase persisted and returned custom Gemini questions in interview_questions');

  // 3. Candidate turn interaction via HTTP Route Handler
  const interactReq = new Request(`http://localhost:3000/api/interviews/${created.token}/interact`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      questionId: question1.id,
      answerText: 'We configure Horizontal Pod Autoscaler based on custom Prometheus metrics and utilize Karpenter for dynamic EC2 node provisioning.',
      timeSpentSeconds: 150,
      totalElapsedSeconds: 300,
    })
  });

  const interactRes = await interactApi(interactReq, { params: Promise.resolve({ token: created.token }) });
  assert(interactRes.status === 200, 
    `POST /api/interviews/[token]/interact succeeded (HTTP ${interactRes.status})`);
  const interactBody = await interactRes.json();
  assert(typeof interactBody.interviewerFeedback === 'string' && interactBody.interviewerFeedback.length > 5, 
    'Candidate interaction endpoint returned live conversational feedback');

  // 4. Candidate completes interview via PATCH endpoint (triggers server-side Gemini evaluation)
  const patchReq = new Request(`http://localhost:3000/api/interviews/${created.token}`, {
    method: 'PATCH',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      status: 'completed',
      elapsedSeconds: 600,
      answers: candidateAnswers,
    })
  });

  const patchRes = await patchInterviewApi(patchReq, { params: Promise.resolve({ token: created.token }) });
  assert(patchRes.status === 200, 
    `PATCH /api/interviews/[token] succeeded with completion (HTTP ${patchRes.status})`);
  const patchBody = await patchRes.json();
  assert(patchBody.status === 'completed', 
    'Interview successfully finalized as completed in Supabase');

  // 5. SECURITY CHECK: Ensure candidate GET endpoint NEVER leaks recruiter report or evaluations
  const candidateGetReq = new Request(`http://localhost:3000/api/interviews/${created.token}`);
  const candidateGetRes = await getInterviewApi(candidateGetReq, { params: Promise.resolve({ token: created.token }) });
  const candidatePayload = await candidateGetRes.json();
  assert(candidatePayload.recruiterReport === undefined, 
    'CRITICAL SECURITY: Candidate GET endpoint NEVER leaks recruiterReport');
  assert(candidatePayload.detailedEvaluation === undefined, 
    'CRITICAL SECURITY: Candidate GET endpoint NEVER leaks detailedEvaluation');

  // 6. RECRUITER VERIFICATION: Recruiter query includes full Gemini evaluation and score
  const recruiterInterviews = await getRecruiterInterviewsFromDb(recruiterId);
  const recruiterRecord = recruiterInterviews.find(i => i.id === created.id);
  assert(!!recruiterRecord && recruiterRecord.status === 'completed', 
    'Recruiter can query completed interview from Supabase');
  assert(!!recruiterRecord?.recruiterReport, 
    'Recruiter record contains comprehensive recruiter evaluation');
  assert(typeof recruiterRecord?.recruiterReport?.overallScore === 'number', 
    `Recruiter record includes Gemini overall score: ${recruiterRecord?.recruiterReport?.overallScore}/100`);
  assert(!!recruiterRecord?.recruiterReport?.detailedEvaluation?.competencies, 
    'Recruiter record includes 6-competency scorecard breakdown');

  // --------------------------------------------------------------------------
  // SUMMARY
  // --------------------------------------------------------------------------
  console.log('\n======================================================');
  console.log(`📊 LIVE GEMINI SUITE SUMMARY: ${passed} PASSED, ${failed} FAILED`);
  console.log('======================================================\n');

  if (failed > 0) process.exit(1);
}

runLiveGeminiSuite().catch(err => {
  console.error('Fatal live Gemini test runner error:', err);
  process.exit(1);
});
